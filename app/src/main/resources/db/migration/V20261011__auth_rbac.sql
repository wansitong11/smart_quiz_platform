-- =============================================================================
-- 登录鉴权与 RBAC 权限模型
--   users            账号
--   roles            角色（RBAC 的角色）
--   permissions      权限点（功能级权限，不含数据行级隔离）
--   user_roles       用户-角色
--   role_permissions 角色-权限
--   refresh_tokens   刷新令牌白名单（双 Token 机制的续期凭证）
-- =============================================================================

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  display_name VARCHAR(64),
  email VARCHAR(128),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  -- 踢人下线用：递增即让该用户签发的全部 Access Token 失效
  token_version INTEGER NOT NULL DEFAULT 0,
  last_login_at TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6),
  CONSTRAINT uk_users_username UNIQUE (username),
  CONSTRAINT users_status_check CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL,
  name VARCHAR(64) NOT NULL,
  description VARCHAR(255),
  system_role BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_roles_code UNIQUE (code)
);

CREATE TABLE permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL,
  name VARCHAR(64) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_permissions_code UNIQUE (code)
);

CREATE TABLE user_roles (
  user_id BIGINT NOT NULL,
  role_id BIGINT NOT NULL,
  PRIMARY KEY (user_id, role_id),
  CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE
);

CREATE TABLE role_permissions (
  role_id BIGINT NOT NULL,
  permission_id BIGINT NOT NULL,
  PRIMARY KEY (role_id, permission_id),
  CONSTRAINT fk_role_permissions_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE,
  CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id) REFERENCES permissions (id) ON DELETE CASCADE
);

CREATE TABLE refresh_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  -- 令牌标识（明文，作为查询键），与客户端持有的 secret 组成完整刷新令牌
  token_id VARCHAR(64) NOT NULL,
  -- 只存 secret 的 SHA-256，库被读也无法直接冒用
  token_hash VARCHAR(128) NOT NULL,
  user_agent VARCHAR(255),
  client_ip VARCHAR(64),
  issued_at TIMESTAMP(6) NOT NULL,
  expires_at TIMESTAMP(6) NOT NULL,
  revoked_at TIMESTAMP(6),
  replaced_by VARCHAR(64),
  CONSTRAINT uk_refresh_tokens_token_id UNIQUE (token_id),
  CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);
