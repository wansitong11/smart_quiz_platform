-- 图片 / 扫描件试卷识别：页级状态 + 试卷识别任务字段 + 视觉 Provider 能力标记

ALTER TABLE practice_papers
  ADD COLUMN recognition_status VARCHAR(20) NOT NULL DEFAULT 'NONE',
  ADD COLUMN recognition_error VARCHAR(500),
  ADD COLUMN page_count INTEGER,
  ADD COLUMN recognition_attempt_id VARCHAR(36),
  ADD COLUMN recognition_updated_at TIMESTAMP(6),
  ADD COLUMN recognition_recovery_count INTEGER NOT NULL DEFAULT 0;

CREATE TABLE paper_pages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_id BIGINT NOT NULL,
  page_no INTEGER NOT NULL,
  source VARCHAR(8) NOT NULL,
  status VARCHAR(16) NOT NULL,
  text_content TEXT,
  has_figure BOOLEAN NOT NULL DEFAULT false,
  notes VARCHAR(500),
  image_key VARCHAR(500),
  model VARCHAR(128),
  error VARCHAR(500),
  attempt INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMP(6) NOT NULL DEFAULT now(),
  CONSTRAINT uk_paper_page UNIQUE (paper_id, page_no),
  CONSTRAINT fk_paper_page_paper
    FOREIGN KEY (paper_id) REFERENCES practice_papers(id) ON DELETE CASCADE
);

CREATE INDEX idx_paper_pages_status ON paper_pages (paper_id, status);

ALTER TABLE llm_provider_config
  ADD COLUMN supports_vision BOOLEAN NOT NULL DEFAULT false;

ALTER TABLE llm_global_setting
  ADD COLUMN default_vision_provider_id VARCHAR(64);
