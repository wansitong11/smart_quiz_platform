-- 复杂试卷：文档类型、页面资源、结构预览缓存

ALTER TABLE practice_papers
  ADD COLUMN source_type VARCHAR(16) NOT NULL DEFAULT 'PDF',
  ADD COLUMN structure_json TEXT,
  ADD COLUMN structure_hash VARCHAR(64);

ALTER TABLE paper_pages
  ADD COLUMN assets_json TEXT,
  ADD COLUMN line_start INTEGER,
  ADD COLUMN line_count INTEGER,
  ADD COLUMN logical_page BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE paper_assets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_id BIGINT NOT NULL,
  page_no INTEGER,
  asset_key VARCHAR(64) NOT NULL,
  parent_key VARCHAR(64),
  kind VARCHAR(24) NOT NULL,
  role VARCHAR(16),
  storage_key VARCHAR(500),
  rect_json VARCHAR(200),
  anchor_text VARCHAR(300),
  anchor_line INTEGER,
  layout VARCHAR(16),
  option_count INTEGER,
  cut_offsets VARCHAR(500),
  width INTEGER,
  height INTEGER,
  created_at TIMESTAMP(6) NOT NULL DEFAULT now(),
  CONSTRAINT uk_paper_asset UNIQUE (paper_id, asset_key),
  CONSTRAINT fk_paper_asset_paper
    FOREIGN KEY (paper_id) REFERENCES practice_papers(id) ON DELETE CASCADE
);

CREATE INDEX idx_paper_assets_paper ON paper_assets (paper_id);
